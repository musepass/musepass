#!/usr/bin/env node
/**
 * Give the web app the anchor ledger, with the records each anchor covers.
 *
 * The ledger is the repo's record of what we anchored; the records are what the
 * root was built from. Shipping both lets the anchors page recompute the root in
 * the browser, which is the only interesting thing a reader can do with it: if
 * the records do not hash to the anchored root, the page says so.
 *
 *   node scripts/generate-web-anchors.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..');

const chains = JSON.parse(readFileSync(resolve(repoRoot, 'config/chains.json'), 'utf8'));
const ledger = JSON.parse(readFileSync(resolve(repoRoot, 'deployments/receipt-anchors.json'), 'utf8'));

const entries = ledger.map((anchor) => {
  const records = JSON.parse(readFileSync(resolve(repoRoot, anchor.records), 'utf8'));
  return {
    chainId: anchor.chainId,
    chainName: chains.l2.name,
    explorer: chains.l2.explorer,
    tx: anchor.tx,
    root: anchor.root,
    count: anchor.count,
    anchoredAt: anchor.anchoredAt,
    block: anchor.block,
    recordsPath: anchor.records,
    records,
  };
});

const body = `/**
 * GENERATED by scripts/generate-web-anchors.mjs — do not edit by hand.
 *
 * One entry per anchored batch: the transaction that put the root on chain, the
 * root itself, and the records it covers. The web test recomputes every root
 * from the records, so a ledger that drifted from its batches fails loudly.
 */
export interface AnchorLedgerEntry {
  chainId: number;
  chainName: string;
  explorer: string;
  tx: \`0x\${string}\`;
  root: \`0x\${string}\`;
  count: number;
  anchoredAt: number;
  block: number;
  recordsPath: string;
  records: Array<Record<string, unknown>>;
}

export const ANCHOR_LEDGER: AnchorLedgerEntry[] = ${JSON.stringify(entries, null, 2)};
`;

const target = resolve(repoRoot, 'apps/web/lib/anchorLedger.ts');
writeFileSync(target, body);
console.log(`wrote ${target} (${entries.length} anchors)`);
for (const entry of entries) console.log(`  ${entry.tx}  root ${entry.root}  ${entry.count} records`);
