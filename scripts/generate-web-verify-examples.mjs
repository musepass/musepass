#!/usr/bin/env node
/**
 * Two conformance vectors, copied into the web app so the verify page can show
 * a real example without a network call.
 *
 * They stay the draft's vectors, not ours: one passes, one is refuted. The web
 * test suite re-reads the fixtures and fails if these copies drift.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..');
const fixtures = resolve(repoRoot, 'packages/verify/test/fixtures/erc8412');

const names = ['valid-satisfied', 'o2-met-without-evidence'];
const loaded = names.map((name) => ({
  name,
  vector: JSON.parse(readFileSync(resolve(fixtures, `${name}.json`), 'utf8')),
}));

const body = `/**
 * GENERATED by scripts/generate-web-verify-examples.mjs — do not edit by hand.
 *
 * Two packages from the ERC-8412 draft's own conformance vectors (CC0), pinned
 * with the rest of them in packages/verify/test/fixtures/erc8412. One is
 * well formed, one is refuted: paste either into the verify page to see the
 * difference. They are examples of the draft's rules, not of our product.
 */
export const VERIFY_EXAMPLES = ${JSON.stringify(
  Object.fromEntries(loaded.map(({ name, vector }) => [name, vector])),
  null,
  2,
)} as const;
`;

const target = resolve(repoRoot, 'apps/web/lib/verifyExamples.ts');
writeFileSync(target, body);
console.log(`wrote ${target} (${Object.keys(loaded).length} examples)`);
