#!/usr/bin/env node
/**
 * Copy the vendored L1 resolver bytecode into apps/web, where the browser can
 * reach it.
 *
 * The web app has to be able to send the deployment transaction itself, so the
 * bytecode has to ship with the page. A copy can drift from the original, so the
 * web test suite compares the two and fails if they ever differ:
 *
 *   pnpm --filter @musename/web test
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..');
const source = resolve(repoRoot, 'contracts/lib/durin-L1Resolver.deployable.txt');
const target = resolve(repoRoot, 'apps/web/lib/l1ResolverBytecode.ts');

const bytecode = readFileSync(source, 'utf8').trim();
if (!/^0x[0-9a-fA-F]+$/.test(bytecode)) {
  throw new Error(`${source} does not look like bytecode`);
}

const body = `/**
 * GENERATED by scripts/generate-web-bytecode.mjs — do not edit by hand.
 *
 * Durin's L1Resolver creation code with the original constructor arguments
 * stripped. Provenance is written up in contracts/lib/README.md; the web test
 * suite re-reads that file and fails if this copy ever drifts from it.
 */
export const L1_RESOLVER_BYTECODE =
  '${bytecode}' as \`0x\${string}\`;
`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, body);
console.log(`wrote ${target} (${(bytecode.length - 2) / 2} bytes)`);
